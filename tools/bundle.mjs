// Concatenate the ES-module sources in /src into one classic script so the page
// also works when index.html is opened directly from disk (file://).
// Usage: node tools/bundle.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const order = ['forms.js', 'strand.js', 'data.js', 'main.js'];
const body = order.map((f) => {
  const src = readFileSync(join(root, 'src', f), 'utf8')
    .replace(/^import[\s\S]*?from\s+['"][^'"]+['"];\s*$/gm, '')
    .replace(/^export\s+(?=(const|function|class|let)\b)/gm, '');
  return `/* ---- ${f} ---- */\n${src}`;
}).join('\n');
const out = `/* Pantone3D — generated by tools/bundle.mjs from /src. Do not edit directly. */\n(function () {\n'use strict';\n${body}\n})();\n`;
writeFileSync(join(root, 'assets', 'js', 'app.js'), out);
console.log('assets/js/app.js', out.length, 'bytes');
